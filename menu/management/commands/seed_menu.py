class Command(BaseCommand):
    help = 'Заполнение БД тестовыми данными меню и создание суперпользователя'

    def handle(self, *args, **options):
        User = get_user_model()

        # Суперпользователь
        if not User.objects.filter(username='Admin').exists():
            User.objects.create_superuser('Admin', 'admin@bbcoffee.ru', 'admin123')
            self.stdout.write(self.style.SUCCESS('Суперпользователь Admin создан'))
        else:
            u = User.objects.get(username='Admin')
            u.set_password('admin123')
            u.save()
            self.stdout.write('Пароль Admin обновлён')

        # Меню
        created_cats = 0
        created_items = 0
        for cat_name, data in MENU_DATA.items():
            cat, c_new = Category.objects.get_or_create(
                slug=data['slug'],
                defaults={'name': cat_name, 'order': data['order']}
            )
            if c_new:
                created_cats += 1
            for i, (name, price, desc) in enumerate(data['items']):
                _, i_new = MenuItem.objects.get_or_create(
                    name=name, category=cat,
                    defaults={'price': price, 'description': desc,
                              'order': i, 'is_available': True}
                )
                if i_new:
                    created_items += 1

        self.stdout.write(self.style.SUCCESS(
            f'Готово: {created_cats} категорий, {created_items} позиций добавлено'
        ))
        self.stdout.write(f'Всего в БД: {Category.objects.count()} категорий, {MenuItem.objects.count()} позиций')
